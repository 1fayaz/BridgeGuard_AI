"""The three explanation provenances (specs/005-demo-mode-and-approval §1.3, FR-1.7/FR-1.8).

Never conflated, never mislabelled — a frontend showing "Written by AI" over text that was not,
in fact, generated by a model would be exactly the kind of fabrication this project's own rules
forbid:

- `LIVE_AI` — a real model call succeeded just now. Label: "Written by AI. Not edited."
- `PREGENERATED_AI` — generated once, offline, by the real model for this fixed demo scenario, and
  hand-verified to pass the numeric-provenance guardrail before being stored verbatim. Still
  genuinely AI-authored text, just not generated live. Label: "AI-written explanation, generated in
  advance for this scenario."
- `TEMPLATE_FALLBACK` — not AI output at all. The last-resort text used when `on_model_failure`
  (`orchestrator.py`) fires. Rendered as plain text, never inside the "Written by AI" box.

**Priority order (FR-1.7 item 7): pre-generated is the primary demo path.** `run_slice1`
(`pipeline.py`) defaults to `PregeneratedReasoningModel` — if
`src/demo/pregenerated_explanation.json` exists (written once, offline, by
`scripts/demo/generate_explanation.py`), that stored text is used. If it doesn't exist (not yet
generated), `.draft()` raises and the existing `on_model_failure` hook falls back to
`TEMPLATE_FALLBACK_TEXT` — the same safety net as before, just one layer further down the chain.
A genuinely live call (`LiveReasoningModel`, `live_model.py`) remains fully opt-in — never the
default — and only ever runs on the presenter's laptop.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from enum import Enum
from pathlib import Path
from typing import Any, Final


class ExplanationKind(str, Enum):
    LIVE_AI = "live_ai"
    PREGENERATED_AI = "pregenerated_ai"
    TEMPLATE_FALLBACK = "template_fallback"


LIVE_AI_LABEL: Final = "Written by AI. Not edited."
PREGENERATED_AI_LABEL: Final = "AI-written explanation, generated in advance for this scenario."
TEMPLATE_FALLBACK_TEXT: Final = "Template explanation: AI unavailable."

LABELS: Final[dict[ExplanationKind, str]] = {
    ExplanationKind.LIVE_AI: LIVE_AI_LABEL,
    ExplanationKind.PREGENERATED_AI: PREGENERATED_AI_LABEL,
    ExplanationKind.TEMPLATE_FALLBACK: TEMPLATE_FALLBACK_TEXT,
}


def template_fallback_hook(exc: Exception) -> str:
    """The `on_model_failure` hook passed to `assess_bridge` (orchestrator.py) for today's build
    step. Ignores the exception's text deliberately — nothing exception-derived ever reaches a
    client-visible field (the same discipline `status_policy.py` already enforces at the API
    boundary)."""
    return TEMPLATE_FALLBACK_TEXT


class NotWiredModel:
    """Always fails — explicitly opt in to this (pass `model=NotWiredModel()`) to force the
    template-fallback path regardless of whether a pre-generated explanation exists, e.g. for a
    test that specifically wants to exercise that path."""

    def draft(self, attempt: int, context: dict) -> str:
        raise NotImplementedError("NotWiredModel always fails by design")


# Written once, offline, by scripts/demo/generate_explanation.py — never hand-edited.
PREGENERATED_EXPLANATION_PATH: Final = (
    Path(__file__).resolve().parent / "pregenerated_explanation.json"
)


@dataclass(frozen=True, slots=True)
class PregeneratedExplanation:
    text: str
    provider: str
    model: str
    generated_at: str
    guardrail_passed: bool


def load_pregenerated_explanation(
    path: Path = PREGENERATED_EXPLANATION_PATH,
) -> PregeneratedExplanation | None:
    """Read the stored pre-generated explanation, or None if it hasn't been generated yet.

    Deliberately permissive about absence (returns None, doesn't raise) — a missing file is the
    expected state before `generate_explanation.py` has ever been run, not an error. A present but
    malformed file DOES raise (ValueError/KeyError) — that is a real data problem, not "not yet
    generated," and should be loud rather than silently treated as absent.
    """
    if not path.exists():
        return None
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return PregeneratedExplanation(
        text=data["text"], provider=data["provider"], model=data["model"],
        generated_at=data["generated_at"], guardrail_passed=data["guardrail_passed"],
    )


class PregeneratedReasoningModel:
    """The primary demo explanation source (FR-1.7 item 7). `draft()` returns the stored text if
    present; raises if absent, so the existing `on_model_failure` hook (orchestrator.py) catches it
    and falls back to the labelled template — no new failure-handling path, same mechanism as every
    other model-draft failure."""

    def __init__(self, path: Path = PREGENERATED_EXPLANATION_PATH) -> None:
        self._path = path

    def draft(self, attempt: int, context: dict) -> str:
        loaded = load_pregenerated_explanation(self._path)
        if loaded is None:
            raise FileNotFoundError(
                f"no pre-generated explanation at {self._path.name} — run "
                "scripts/demo/generate_explanation.py first, or this falls back to the template"
            )
        if not loaded.guardrail_passed:
            raise ValueError("stored pre-generated explanation did not pass the guardrail check")
        return loaded.text
